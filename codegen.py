def _date_expr(value):
    m = re.fullmatch(r"\s*(\d{4})-(\d{1,2})-(\d{1,2})\s*", value or "")
    if not m:
        return None
    y, mo, d = (int(x) for x in m.groups())
    return f"time.Date({y}, {mo}, {d}, 0, 0, 0, 0, time.UTC)"


