# ---------------------------------------------------------------- identifiers

def _words(name):
    return re.findall(r"[A-Za-z0-9]+", name or "")


def pascal(name):
    out = "".join(w[0].upper() + w[1:] for w in _words(name))
    if not out or not out[0].isalpha():
        out = "Card" + out
    return out


def _lower_head(word):
    run = re.match(r"[A-Z]+", word)
    n = len(run.group(0)) if run else 0
    if n <= 1:
        return word[:1].lower() + word[1:]
    if n == len(word) or word[n].isdigit():
        return word[:n].lower() + word[n:]
    return word[: n - 1].lower() + word[n - 1 :]


def camel(name):
    words = _words(name)
    if not words or not words[0][0].isalpha():
        return _lower_head(pascal(name))
    return _lower_head(words[0][0].upper() + words[0][1:]) + "".join(w[0].upper() + w[1:] for w in words[1:])


def snake(name):
    return "_".join(w.lower() for w in _words(name)) or "card"


def card_idents(design):
    base = design.get("ident") or pascal(design.get("name") or "Card")
    base = pascal(base)
    return {
        "pascal": base,
        "camel": camel(base),
        "snake": snake(re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", base)),
    }


def go_file_name(design):
    return f"{card_idents(design)['snake']}_card_image.go"


# ---------------------------------------------------------------- literals

def num(v):
    v = round(float(v or 0), 3)
    if v == int(v):
        return f"{int(v)}.0"
    return f"{v:.3f}".rstrip("0")


def go_str(s):
    return json.dumps(s or "", ensure_ascii=False)


def scaled(v, factor):
    v = float(v or 0)
    return "0.0" if v == 0 else f"{num(v)} * {factor}"


def norm_hex(value, fallback="#000000"):
    value = (value or "").strip()
    if re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        return value.upper()
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        return "#" + "".join(c * 2 for c in value[1:]).upper()
    return fallback


def color_expr(hex_value, opacity=1.0):
    c = f'hexColor("{norm_hex(hex_value)}")'
    opacity = 1.0 if opacity is None else float(opacity)
    if opacity < 1:
        return f"withAlpha({c}, {num(opacity)})"
    return c


TEMPLATE_RE = re.compile(r"\{\{\s*([A-Za-z0-9_]+)((?:\s*\|\s*[a-z]+)*)\s*\}\}")
FILTERS = {
    "upper": "strings.ToUpper({})",
    "lower": "strings.ToLower({})",
    "title": "strings.Title(strings.ToLower({}))",
    "card": "formatCardNumberOrRef({})",
    "date": "formatSaintsDate({})",
    "trim": "strings.TrimSpace({})",
}


def parse_template(text):
    parts, pos = [], 0
    for m in TEMPLATE_RE.finditer(text or ""):
        if m.start() > pos:
            parts.append(("lit", text[pos : m.start()]))
        field = m.group(1)
        if field not in TEMPLATE_FIELDS:
            raise CodegenError(f"Unknown field {{{{{field}}}}} in text {text!r}")
        filters = [f.strip() for f in m.group(2).split("|") if f.strip()]
        for f in filters:
            if f not in FILTERS:
                raise CodegenError(f"Unknown filter |{f} in text {text!r}")
        parts.append(("field", field, filters))
        pos = m.end()
    if pos < len(text or ""):
        parts.append(("lit", text[pos:]))
    return parts


def template_expr(text):
    exprs = []
    for part in parse_template(text):
        if part[0] == "lit":
            exprs.append(go_str(part[1]))
        else:
            e = f"data.{part[1]}"
            for f in part[2]:
                e = FILTERS[f].format(e)
            exprs.append(e)
    return " + ".join(exprs) if exprs else '""'


def template_fields(text):
    return [p[1] for p in parse_template(text) if p[0] == "field"]


SINGLE_FIELD_RE = re.compile(r"^\s*\{\{\s*([A-Za-z0-9_]+)\s*\}\}\s*$")


# ---------------------------------------------------------------- elements

BOX_TYPES = {"image", "rect", "avatar"}
SQUARE_TYPES = {"circle", "qr"}
TEXT_TYPES = {"text", "rich"}


def is_square(el):
    return el["type"] in SQUARE_TYPES or (el["type"] == "avatar" and el.get("shape") == "circle")


def is_multiline(el):
    return el["type"] == "text" and (el.get("wrap", "none") != "none" or "\n" in (el.get("text") or ""))


def is_drawable(el):
    if el.get("hidden"):
        return False
    if el["type"] in ("rect", "circle"):
        return bool(el.get("fill") or (el.get("stroke") and float(el.get("strokeWidth") or 0) > 0))
    return True


def indent(lines, n=1):
    return [("\t" * n + l) if l else l for l in lines]


def rotate_wrap(body, deg, cx, cy):
    deg = float(deg or 0)
    if deg % 360 == 0:
        return body
    return ["dc.Push()", f"dc.RotateAbout(gg.Radians({num(deg)}), {cx}, {cy})"] + body + ["dc.Pop()"]


class FaceGen:
    def __init__(self, card, face, consts):
        self.card = card
        self.face = face
        self.consts = consts  # shared asset constants: key -> const name
        self.vars = {}  # element id -> var base
        self.used_bases = set()
        elements = [e for e in face.get("elements", []) if is_drawable(e)]
        self.elements = elements
        self.order = {e["id"]: i for i, e in enumerate(elements)}
        self.by_id = {e["id"]: e for e in elements}
        self.anchors = set()
        for i, el in enumerate(elements):
            self.vars[el["id"]] = self._base(el, i)
        for el in elements:
            target = self._attach_target(el)
            if target:
                self.anchors.add(target["id"])

    def _base(self, el, i):
        base = camel(el.get("name") or f"{el['type']} {i + 1}")
        candidate, n = base, 2
        while candidate.lower() in self.used_bases:
            candidate, n = f"{base}{n}", n + 1
        self.used_bases.add(candidate.lower())
        return candidate

    def _attach_target(self, el):
        attach = el.get("attach") or {}
        target = self.by_id.get(attach.get("to"))
        if not target or self.order[target["id"]] >= self.order[el["id"]]:
            return None
        return target

    def _anchor_expr(self, target):
        tv = self.vars[target["id"]]
        if target["type"] in TEXT_TYPES:
            return f"{tv}BottomY" if is_multiline(target) else f"{tv}Y"
        if is_square(target):
            return f"{tv}Y + {tv}Size"
        return f"{tv}Y + {tv}H"

    def y_expr(self, el):
        target = self._attach_target(el)
        if not target:
            return scaled(el.get("y"), "sy")
        offset = float((el.get("attach") or {}).get("offset") or 0)
        anchor = self._anchor_expr(target)
        if offset == 0:
            return anchor
        if offset < 0:
            return f"{anchor} - {num(-offset)}*sy"
        return f"{anchor} + {num(offset)}*sy"

    def asset_const(self, key, el, suffix="URL"):
        key = (key or "").strip()
        if not key:
            return '""'
        m = SINGLE_FIELD_RE.match(key)
        if m:
            field = m.group(1)
            if field not in TEMPLATE_FIELDS:
                raise CodegenError(f"Unknown field {{{{{field}}}}} used as image source")
            return f"data.{field}"
        if key not in self.consts:
            name = f"{self.card['camel']}{pascal(el.get('name') or el['type'])}{suffix}"
            taken = set(self.consts.values())
            candidate, n = name, 2
            while candidate in taken:
                candidate, n = f"{name}{n}", n + 1
            self.consts[key] = candidate
        return self.consts[key]

    # -- per element ---------------------------------------------------------

    def gen(self, el):
        label = (el.get("name") or el["type"]).replace("\n", " ")
        fn = getattr(self, f"gen_{el['type']}")
        return [f"// {label}"] + fn(el, self.vars[el["id"]])

    def _box_vars(self, el, v):
        return [
            f"{v}X := {scaled(el.get('x'), 'sx')}",
            f"{v}Y := {self.y_expr(el)}",
            f"{v}W := {scaled(el.get('w'), 'sx')}",
            f"{v}H := {scaled(el.get('h'), 'sy')}",
        ]

    def _square_vars(self, el, v):
        return [
            f"{v}X := {scaled(el.get('x'), 'sx')}",
            f"{v}Y := {self.y_expr(el)}",
            f"{v}Size := {scaled(el.get('w'), 'sc')}",
        ]

    def _fill_stroke(self, el, path):
        body = [path]
        fill = el.get("fill")
        stroke = el.get("stroke") if float(el.get("strokeWidth") or 0) > 0 else None
        if fill:
            body += [f"dc.SetColor({color_expr(fill, el.get('fillOpacity', 1))})", "dc.FillPreserve()" if stroke else "dc.Fill()"]
        if stroke:
            body += [
                f"dc.SetColor({color_expr(stroke, el.get('strokeOpacity', 1))})",
                f"dc.SetLineWidth({scaled(el.get('strokeWidth'), 'sc')})",
                "dc.Stroke()",
            ]
        return body

    def gen_image(self, el, v):
        out = self._box_vars(el, v)
        src = self.asset_const(el.get("src"), el)
        body = []
        if el.get("autoCrop"):
            body.append("img = autoCropNonEmpty(img)")
        if el.get("tint"):
            body.append(f'img = tintImageToColor(img, "{norm_hex(el["tint"])}")')
        fit = el.get("fit", "contain")
        if fit == "cover":
            draw = f"drawImageCover(dc, img, {v}X, {v}Y, {v}W, {v}H)"
        elif fit == "stretch":
            draw = (
                f"dc.DrawImage(scaleImageHighQuality(img, int(math.Round({v}W)), int(math.Round({v}H))), "
                f"int(math.Round({v}X)), int(math.Round({v}Y)))"
            )
        else:
            draw = f"drawImageContain(dc, img, {v}X, {v}Y, {v}W, {v}H)"
        body += rotate_wrap([draw], el.get("rotation"), f"{v}X+{v}W/2", f"{v}Y+{v}H/2")
        out.append(f"if img, err := loadImageFromURIOrURL({src}); err == nil && img != nil {{")
        out += indent(body)
        if el.get("fallbackColor"):
            out += [
                "} else {",
                f"\tdc.SetColor({color_expr(el['fallbackColor'])})",
                f"\tdc.DrawRectangle({v}X, {v}Y, {v}W, {v}H)",
                "\tdc.Fill()",
            ]
        out.append("}")
        return out

    def gen_rect(self, el, v):
        out = self._box_vars(el, v)
        r = float(el.get("radius") or 0)
        path = (
            f"dc.DrawRoundedRectangle({v}X, {v}Y, {v}W, {v}H, {scaled(r, 'sc')})"
            if r > 0
            else f"dc.DrawRectangle({v}X, {v}Y, {v}W, {v}H)"
        )
        out += rotate_wrap(self._fill_stroke(el, path), el.get("rotation"), f"{v}X+{v}W/2", f"{v}Y+{v}H/2")
        return out

    def gen_circle(self, el, v):
        out = self._square_vars(el, v)
        out += self._fill_stroke(el, f"dc.DrawCircle({v}X+{v}Size/2, {v}Y+{v}Size/2, {v}Size/2)")
        return out

    def gen_avatar(self, el, v):
        src = self.asset_const(el.get("src") or "{{AvatarURL}}", el)
        if el.get("shape") == "circle":
            out = self._square_vars(el, v)
            border = el.get("stroke") or "#FFFFFF"
            out.append(
                f"cardUIDrawCircleAvatar(dc, {v}X+{v}Size/2, {v}Y+{v}Size/2, {v}Size/2, {src}, data.Initials, "
                f"{color_expr(border)}, {scaled(el.get('strokeWidth'), 'sc')})"
            )
            return out
        out = self._box_vars(el, v)
        out.append(f"drawRectangularAvatar(dc, {v}X, {v}Y, {v}W, {v}H, {src}, data.Initials)")
        return out

    def gen_qr(self, el, v):
        out = self._square_vars(el, v)
        if el.get("panel", True):
            out.append(
                f"drawRoundedPanel(dc, {v}X, {v}Y, {v}Size, {v}Size, {scaled(el.get('radius'), 'sc')}, "
                f"{color_expr(el.get('panelColor') or '#FFFFFF')})"
            )
        out.append(f"{v}Pad := {scaled(el.get('padding'), 'sc')}")
        if el.get("source") == "vds":
            load = "loadImageOrGenerateVDSQRCode(data.OneIDQRCode, 2400)"
        else:
            load = "loadImageOrGeneratePaymentQRCode(data.PaymentQRCode, 1800)"
        out.append(f"if qrImg, err := {load}; err == nil && qrImg != nil {{")
        if el.get("forceBlack") and el.get("source") != "vds":
            out.append("\tqrImg = ensureBlackQRCodeImage(qrImg)")
        out.append(f"\tdrawImageContain(dc, qrImg, {v}X+{v}Pad, {v}Y+{v}Pad, {v}Size-{v}Pad*2, {v}Size-{v}Pad*2)")
        out.append("}")
        logo = el.get("logo") or {}
        if (logo.get("src") or "").strip():
            src = self.asset_const(logo["src"], el, suffix="LogoURL")
            lp = float(logo.get("padding") or 0)
            out += [
                f"{v}LogoSize := {scaled(logo.get('size'), 'sc')}",
                f"{v}LogoX := {v}X + ({v}Size-{v}LogoSize)/2",
                f"{v}LogoY := {v}Y + ({v}Size-{v}LogoSize)/2",
                f"drawRoundedPanel(dc, {v}LogoX, {v}LogoY, {v}LogoSize, {v}LogoSize, {scaled(logo.get('radius'), 'sc')}, "
                f"{color_expr(logo.get('panelColor') or '#FFFFFF')})",
                f"if logoImg, err := loadImageFromURIOrURL({src}); err == nil && logoImg != nil {{",
            ]
            if lp:
                out += [
                    f"\t{v}LogoPad := {scaled(lp, 'sc')}",
                    f"\tdrawImageContain(dc, logoImg, {v}LogoX+{v}LogoPad, {v}LogoY+{v}LogoPad, "
                    f"{v}LogoSize-{v}LogoPad*2, {v}LogoSize-{v}LogoPad*2)",
                ]
            else:
                out.append(f"\tdrawImageContain(dc, logoImg, {v}LogoX, {v}LogoY, {v}LogoSize, {v}LogoSize)")
            out.append("}")
        return out

    def _hide_cond(self, el, texts):
        if not el.get("hideIfEmpty"):
            return None
        fields = []
        for t in texts:
            for f in template_fields(t):
                if f not in fields:
                    fields.append(f)
        if not fields:
            return None
        return " && ".join(f'strings.TrimSpace(data.{f}) != ""' for f in fields)

    def gen_text(self, el, v):
        text = el.get("text") or ""
        expr = template_expr(text)
        font = el.get("font") if el.get("font") in FONTS else "AptosRegular"
        size = scaled(el.get("size") or 12, "sc")
        clr = color_expr(el.get("color") or "#000000", el.get("opacity", 1))
        ax = num(el.get("ax", 0))
        ay = num(el.get("ay", 0.5))
        grad = el.get("gradient") or {}
        gradient = bool(grad.get("enabled"))
        if gradient:
            g_args = f'"{norm_hex(grad.get("top"))}", "{norm_hex(grad.get("bottom"))}", {num(grad.get("stop", 0))}'
        out = [f"{v}X := {scaled(el.get('x'), 'sx')}", f"{v}Y := {self.y_expr(el)}"]
        cond = self._hide_cond(el, [text])
        wants_bottom = el["id"] in self.anchors

        if not is_multiline(el):
            if gradient:
                draw = f"drawVerticalGradientText(dc, {expr}, {v}X, {v}Y, mustFont(fonts.{font}, {size}), {g_args}, {ax}, 0.5)"
            else:
                draw = f"drawText(dc, {expr}, {v}X, {v}Y, mustFont(fonts.{font}, {size}), {clr}, {ax}, {ay})"
            body = rotate_wrap([draw], el.get("rotation"), f"{v}X", f"{v}Y")
            if cond:
                return out + [f"if {cond} {{"] + indent(body) + ["}"]
            return out + body

        wrap = el.get("wrap", "none")
        max_w = scaled(el.get("maxWidth") or 0, "sx")
        max_lines = int(el.get("maxLines") or 2)
        body = []
        if wrap == "fit":
            body.append(
                f"{v}Lines, {v}Face := cardUIFitLines(dc, {expr}, {max_w}, fonts.{font}, {size}, "
                f"{scaled(el.get('minSize') or el.get('size'), 'sc')}, {scaled(el.get('step') or 1, 'sc')}, {max_lines})"
            )
        else:
            body.append(f"{v}Face := mustFont(fonts.{font}, {size})")
            if wrap == "balance":
                body += [f"dc.SetFontFace({v}Face)", f"{v}Lines := splitNameToLines(dc, {expr}, {max_w})"]
            elif wrap == "wrap":
                body += [f"dc.SetFontFace({v}Face)", f"{v}Lines := cardUIWrapLines(dc, {expr}, {max_w}, {max_lines})"]
            else:
                body.append(f'{v}Lines := strings.Split({expr}, "\\n")')
        body.append(f"{v}Spacing := {scaled(el.get('lineSpacing') or el.get('size') or 12, 'sy')}")
        valign = el.get("valign", "top")
        if valign == "middle":
            body.append(f"{v}StartY := {v}Y - float64(len({v}Lines)-1)*{v}Spacing/2")
        elif valign == "bottom":
            body.append(f"{v}StartY := {v}Y - float64(len({v}Lines)-1)*{v}Spacing")
        else:
            body.append(f"{v}StartY := {v}Y")
        line_y = f"{v}StartY+float64(i)*{v}Spacing"
        if gradient and float(el.get("ax", 0)) == 0:
            draw = [f"drawVerticalGradientLines(dc, {v}Lines, {v}X, {v}StartY, {v}Spacing, {v}Face, {g_args}, 0, 0.5)"]
        elif gradient:
            draw = [
                f"for i, line := range {v}Lines {{",
                f"\tdrawVerticalGradientText(dc, line, {v}X, {line_y}, {v}Face, {g_args}, {ax}, 0.5)",
                "}",
            ]
        else:
            draw = [
                f"for i, line := range {v}Lines {{",
                f"\tdrawText(dc, line, {v}X, {line_y}, {v}Face, {clr}, {ax}, {ay})",
                "}",
            ]
        body += rotate_wrap(draw, el.get("rotation"), f"{v}X", f"{v}Y")
        bottom = f"{v}StartY + float64(len({v}Lines)-1)*{v}Spacing"
        if cond:
            if wants_bottom:
                out.append(f"{v}BottomY := {v}Y")
                body.append(f"{v}BottomY = {bottom}")
            return out + [f"if {cond} {{"] + indent(body) + ["}"]
        if wants_bottom:
            body.append(f"{v}BottomY := {bottom}")
        return out + body

    def gen_rich(self, el, v):
        segments = el.get("segments") or []
        out = [f"{v}X := {scaled(el.get('x'), 'sx')}", f"{v}Y := {self.y_expr(el)}"]
        seg_lines = []
        for seg in segments:
            font = seg.get("font") if seg.get("font") in FONTS else "AptosRegular"
            seg_lines.append(
                f"\t{{Text: {template_expr(seg.get('text') or '')}, "
                f"Face: mustFont(fonts.{font}, {scaled(seg.get('size') or 12, 'sc')}), "
                f"Color: {color_expr(seg.get('color') or '#000000', seg.get('opacity', 1))}}},"
            )
        call = (
            ["cardUIDrawSegments(dc, []cardUITextSegment{"]
            + seg_lines
            + [f"}}, {v}X, {v}Y, {num(el.get('ax', 0))}, {num(el.get('ay', 0.5))})"]
        )
        body = rotate_wrap(call, el.get("rotation"), f"{v}X", f"{v}Y")
        cond = self._hide_cond(el, [s.get("text") or "" for s in segments])
        if cond:
            return out + [f"if {cond} {{"] + indent(body) + ["}"]
        return out + body

    # -- whole face ----------------------------------------------------------

    def function_name(self):
        return f"draw{self.card['pascal']}Card{pascal(self.face.get('name') or self.face['id'])}"

    def const_prefix(self):
        return f"{self.card['camel']}{pascal(self.face.get('name') or self.face['id'])}"

    def generate(self):
        face = self.face
        body = []
        if face.get("background"):
            body += [
                "",
                f"dc.SetColor({color_expr(face['background'])})",
                "dc.DrawRectangle(0, 0, float64(w), float64(h))",
                "dc.Fill()",
            ]
        for el in self.elements:
            body += [""] + self.gen(el)
        clip = float(face.get("clipRadius") or 0)
        image_expr = f"cardUIRoundCorners(dc.Image(), {scaled(clip, 'sc')})" if clip > 0 else "dc.Image()"
        face_label = (face.get("name") or face["id"]).lower()
        message = go_str(f"encode {self.card['name'].lower()} {face_label} image: %w")
        body += [
            "",
            "var out bytes.Buffer",
            f"if err := png.Encode(&out, {image_expr}); err != nil {{",
            f"\treturn nil, fmt.Errorf({message}, err)",
            "}",
            "return out.Bytes(), nil",
        ]
        text = "\n".join(body)
        uses = lambda tok: re.search(rf"\b{tok}\b", _strip_strings(text)) is not None
        need_sc = uses("sc")
        scale = []
        if uses("sx") or need_sc:
            scale.append(f"sx := float64(w) / {num(face['designW'])}")
        if uses("sy") or need_sc:
            scale.append(f"sy := float64(h) / {num(face['designH'])}")
        if need_sc:
            scale.append("sc := math.Min(sx, sy)")
        prefix = self.const_prefix()
        head = [
            f"func {self.function_name()}(data employeeCardTemplateData) ([]byte, error) {{",
            f"\tw, h := {prefix}W, {prefix}H",
            "\tdc := gg.NewContext(w, h)",
        ]
        if scale:
            head += [""] + indent(scale)
        return "\n".join(head + indent(body) + ["}"])


def _strip_strings(code):
    return re.sub(r'"(?:[^"\\\n]|\\.)*"|`[^`]*`', '""', code)


IMPORTS = [
    ("bytes", "bytes"),
    ("fmt", "fmt"),
    ("image/png", "png"),
    ("math", "math"),
    ("strings", "strings"),
    ("employee-card-admin/assets/fonts", "fonts"),
    ("employee-card-admin/dto", "dto"),
    ("employee-card-admin/models", "models"),
    ("github.com/fogleman/gg", "gg"),
]


def _imports_for(code):
    stripped = _strip_strings(code)
    std, local, third = [], [], []
    for path, pkg in IMPORTS:
        if re.search(rf"\b{pkg}\.", stripped):
            if path.startswith("employee-card-admin/"):
                local.append(path)
            elif "." in path.split("/")[0]:
                third.append(path)
            else:
                std.append(path)
    # Same grouping as the hand-written card files.
    lines = [f'\t"{p}"' for p in sorted(local + std)]
    if third:
        lines += [""] + [f'\t"{p}"' for p in third]
    return "import (\n" + "\n".join(lines) + "\n)"


def validate(design):
    faces = design.get("faces") or []
    if not faces:
        raise CodegenError("Design has no faces")
    roles = {}
    for face in faces:
        role = face.get("role") or "none"
        if role != "none":
            if role in roles:
                raise CodegenError(f"Faces {roles[role]!r} and {face.get('name')!r} both use role {role!r}")
            roles[role] = face.get("name")
        for key in ("designW", "designH", "outW", "outH"):
            if not float(face.get(key) or 0) > 0:
                raise CodegenError(f"Face {face.get('name')!r} needs a positive {key}")
    names = [pascal(f.get("name") or f["id"]) for f in faces]
    if len(set(names)) != len(names):
        raise CodegenError("Face names must be unique (they become Go function names)")
    if "payment" not in roles and "oneid" not in roles:
        raise CodegenError("At least one face needs the Payment or OneID role")
    return roles


def field_value_expr(field, cfg):
    cfg = cfg or {}
    mode = cfg.get("mode") or ("fixed" if field["source"] is None else "auto")
    value = cfg.get("value", field["fallback"])
    if mode == "fixed" or field["source"] is None:
        return go_str(value)
    return f"universityFallbackString({field['source']}, {go_str(value)})"


def gen_matcher(card, match):
    designations = [m.strip().lower() for m in (match or {}).get("designation", []) if m.strip()]
    businesses = [m.strip().lower() for m in (match or {}).get("business", []) if m.strip()]
    lines = [
        f"// is{card['pascal']}Card reports whether a member should get the {card['name']} card layout.",
        f"func is{card['pascal']}Card(businessName, designation string) bool {{",
    ]
    if not designations and not businesses:
        lines += ["\treturn false", "}"]
        return "\n".join(lines)
    conds = []
    if businesses:
        lines.append("\tb := strings.ToLower(strings.TrimSpace(businessName))")
        conds += [f"strings.Contains(b, {go_str(m)})" for m in businesses]
    if designations:
        lines.append("\td := strings.ToLower(strings.TrimSpace(designation))")
        conds += [f"strings.Contains(d, {go_str(m)})" for m in designations]
    lines.append("\treturn " + " ||\n\t\t".join(conds))
    lines.append("}")
    return "\n".join(lines)


