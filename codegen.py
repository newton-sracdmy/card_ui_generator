def gen_builder(card, faces):
    role_vars = {}
    lines = [
        f"// Build{card['pascal']}CardImages renders every {card['name']} card face.",
        f"func Build{card['pascal']}CardImages(",
        "\temployee models.Employee,",
        "\tmembership models.Membership,",
        "\tmerchant models.Merchant,",
        "\tdgepayCard dto.GenericResponse,",
        "\tgenerateVDS dto.GenerateVDSData,",
        ") (UniversityCardImages, error) {",
        f"\tdata, err := build{card['pascal']}CardTemplateData(employee, membership, merchant, dgepayCard, generateVDS)",
        "\tif err != nil {",
        "\t\treturn UniversityCardImages{}, err",
        "\t}",
    ]
    for fg in faces:
        role = fg.face.get("role") or "none"
        if role == "none":
            continue
        var = camel(fg.face.get("name") or fg.face["id"]) + "Img"
        role_vars[role] = var
        lines += ["", f"\t{var}, err := {fg.function_name()}(data)"]
        if role == "thumbnail":
            lines += ["\tif err != nil {", f"\t\t{var} = nil", "\t}"]
        else:
            lines += ["\tif err != nil {", "\t\treturn UniversityCardImages{}, err", "\t}"]
    lines += [
        "",
        "\tqrBytes, err := universityPNGBytesFromDataURI(data.OneIDQRCode)",
        "\tif err != nil {",
        "\t\tqrBytes = nil",
        "\t}",
        "",
        "\treturn UniversityCardImages{",
    ]
    for role, field in (("payment", "Payment"), ("oneid", "OneID"), ("thumbnail", "Thumbnail")):
        if role in role_vars:
            lines.append(f"\t\t{field}: {role_vars[role]},")
    lines += ["\t\tOneIDPNGForSyncData: qrBytes,", "\t}, nil", "}"]
    return "\n".join(lines)


def generate(design, source_label=None):
    """Return the card's Go source (unformatted) plus metadata."""
    validate(design)
    card = dict(card_idents(design), name=design.get("name") or "Card")
    consts = {}
    face_gens = [FaceGen(card, face, consts) for face in design["faces"]]
    face_funcs = [fg.generate() for fg in face_gens]

    const_lines = []
    for fg in face_gens:
        prefix = fg.const_prefix()
        const_lines.append(f"\t{prefix}W = {int(round(float(fg.face['outW'])))}")
        const_lines.append(f"\t{prefix}H = {int(round(float(fg.face['outH'])))}")
    for key, name in consts.items():
        const_lines.append(f"\t{name} = {go_str(key)}")

    label = source_label or f"card-ui/designs/{snake(design.get('name') or 'card')}.json"
    parts = [
        gen_matcher(card, design.get("match")),
        gen_builder(card, face_gens),
        gen_template_data(card, design),
    ] + face_funcs
    body = "\n\n".join(parts)
    code = "\n".join(
        [
            f"// {GENERATED_MARK} from {label}.",
            "// Change the design in card-ui and export again instead of editing by hand.",
            "",
            "package card_generator",
            "",
            _imports_for(body),
            "",
            "const (",
            *const_lines,
            ")",
            "",
            body,
            "",
        ]
    )
    declared = (
        [f"is{card['pascal']}Card", f"Build{card['pascal']}CardImages", f"build{card['pascal']}CardTemplateData"]
        + [fg.function_name() for fg in face_gens]
        + [fg.const_prefix() + s for fg in face_gens for s in ("W", "H")]
        + list(consts.values())
    )
    return {
        "code": code,
        "card": card,
        "fileName": go_file_name(design),
        "declared": declared,
        "assets": [k for k in consts if not k.startswith(("http://", "https://", "data:"))],
        "faces": [(fg.face["id"], fg.function_name()) for fg in face_gens],
    }


