def find_collisions(declared, own_file):
    """Names the generated file declares that already exist elsewhere in card_generator."""
    hits = []
    for path in sorted(PKG_DIR.glob("*.go")):
        if path.name in (own_file, HELPERS_FILE):
            continue
        src = path.read_text(errors="replace")
        for name in declared:
            if re.search(rf"^(func\s+{name}\s*\(|\s*{name}\s*=|(const|var|type)\s+{name}\b)", src, re.M):
                hits.append(f"{name} (already declared in card_generator/{path.name})")
    return hits


